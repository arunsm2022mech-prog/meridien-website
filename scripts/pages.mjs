// Builds the two language pages from one template:
//   src/page.html + src/i18n/fr.js  ->  index.html     (French, the default at /)
//   src/page.html + src/i18n/en.js  ->  en/index.html  (English at /en/)
// Placeholders: {{key.path}} inserts the value as HTML, {{key.path|attr}} escapes it for an attribute.
// Runs before `vite` and `vite build` (see package.json). Edit the template or the dictionaries, not the output.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import fr from '../src/i18n/fr.js';
import en from '../src/i18n/en.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const template = readFileSync(resolve(root, 'src/page.html'), 'utf8');

const flatten = (obj, prefix = '') =>
  Object.entries(obj).flatMap(([k, v]) =>
    v && typeof v === 'object' ? flatten(v, `${prefix}${k}.`) : [`${prefix}${k}`]);

// Both languages must define exactly the same keys, so nothing is left untranslated.
const frKeys = new Set(flatten(fr));
const enKeys = new Set(flatten(en));
const onlyFr = [...frKeys].filter((k) => !enKeys.has(k));
const onlyEn = [...enKeys].filter((k) => !frKeys.has(k));
if (onlyFr.length || onlyEn.length) {
  throw new Error(`Translation keys differ.\n  only in fr: ${onlyFr.join(', ') || '-'}\n  only in en: ${onlyEn.join(', ') || '-'}`);
}

const get = (obj, path) => path.split('.').reduce((o, k) => (o == null ? undefined : o[k]), obj);
const escapeAttr = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

const pages = [
  { dict: fr, out: 'index.html' },
  { dict: en, out: 'en/index.html' },
];

for (const { dict, out } of pages) {
  const vars = {
    ...dict,
    cur: {
      fr: dict.lang === 'fr' ? ' aria-current="true"' : '',
      en: dict.lang === 'en' ? ' aria-current="true"' : '',
    },
  };
  const missing = new Set();
  const html = template.replace(/\{\{\s*([\w.]+)(\|attr)?\s*\}\}/g, (match, key, asAttr) => {
    const value = get(vars, key);
    if (value === undefined || (value !== null && typeof value === 'object')) {
      missing.add(key);
      return match;
    }
    return asAttr ? escapeAttr(value) : String(value);
  });
  if (missing.size) throw new Error(`${out}: no value for ${[...missing].join(', ')}`);

  const stamped = html.replace(
    '<!doctype html>\n',
    '<!doctype html>\n<!-- Generated by scripts/pages.mjs from src/page.html and src/i18n/. Edit those files, not this one. -->\n',
  );
  const file = resolve(root, out);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, stamped);
  console.log(`pages: wrote ${out} (${dict.lang})`);
}
